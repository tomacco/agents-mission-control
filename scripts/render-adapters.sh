#!/usr/bin/env bash
# repo-distill: compile the canonical .distill/ source into what each coding agent reads.
#   AGENTS.md                       the cross-tool hub. repo-distill owns ONLY its marked block
#                                   (<!-- repo-distill:start --> ... <!-- repo-distill:end -->): a pointer
#                                   index into .distill/knowledge/. Text outside the block is the humans'
#                                   and other tools' blocks (backlog, ...); it is never touched.
#   CLAUDE.md                       "@AGENTS.md" (created if missing; a block is added if it lacks the import)
#   .github/copilot-instructions.md compiled full copy, owned whole by repo-distill
# Writes .distill/.manifest for the freshness gate (which hashes the block, never the whole file).
#
# Usage: scripts/render-adapters.sh [repo_root]
set -euo pipefail

ROOT="${1:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}"
cd "$ROOT" || { echo "cannot cd $ROOT" >&2; exit 1; }
SRC=".distill"
[ -d "$SRC/knowledge" ] || { echo "no $SRC/knowledge: run distillation first" >&2; exit 1; }

ORDER="architecture conventions workflows gotchas glossary review-culture"
sha() { shasum -a 256 "$@" 2>/dev/null | awk '{print $1}'; }
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BLOCK="python3 $HERE/agents_block.py"
case "$HERE" in "$ROOT"/*) RENDER_CMD="${HERE#"$ROOT"/}/render-adapters.sh";; *) RENDER_CMD="repo-distill render";; esac

# strip frontmatter + html comments (incl. multi-line) + per-fact metadata -> clean prose
strip_one() {
  # 1) drop YAML frontmatter  2) drop HTML comments across lines  3) drop metadata lines
  awk 'NR==1 && $0=="---"{f=1;next} f==1 && $0=="---"{f=0;next} f!=1{print}' "$1" \
    | awk '
        { line=$0; out=""
          while (1) {
            if (inc) { p=index(line,"-->"); if(!p){line="";break} line=substr(line,p+3); inc=0 }
            else     { p=index(line,"<!--"); if(!p){out=out line;break} out=out substr(line,1,p-1); line=substr(line,p+4); inc=1 }
          }
          if (!inc) print out; else if (out !~ /^[[:space:]]*$/) print out
        }' \
    | grep -viE '^[[:space:]]*(confidence|origin|evidence|evidence_says|last_validated|source|src|staleness_threshold|scope|domain):' \
    | cat -s
}

# ordered list of knowledge files: preferred order first, then any extras
list_files() {
  local f
  for n in $ORDER; do [ -f "$SRC/knowledge/$n.md" ] && echo "$SRC/knowledge/$n.md"; done
  for f in "$SRC"/knowledge/*.md; do
    case " $ORDER " in *" $(basename "$f" .md) "*) ;; *) [ -f "$f" ] && echo "$f";; esac
  done
}

FILES=$(list_files)
[ -n "$FILES" ] || { echo "no knowledge files found" >&2; exit 1; }
SRC_SHA=$(printf '%s\n' "$SRC/SPINE.md" $FILES | xargs cat 2>/dev/null | shasum -a 256 | awk '{print $1}')
STAMP=$(git log -1 --format=%cs 2>/dev/null || echo "uncommitted")

BANNER_TOP="<!-- GENERATED by repo-distill. DO NOT EDIT BY HAND.
     Edit the source in .distill/ and run: $RENDER_CMD
     Source hash: $SRC_SHA · repo state: $STAMP -->"

# ---- build the compiled body once ----
BODY=$(mktemp)
{
  echo "# Agent guide for this repository"
  echo
  echo "_Compiled from \`.distill/\` by repo-distill. The canonical, editable source lives in"
  echo "\`.distill/knowledge/\` with provenance. This file is regenerated, and changes here are lost._"
  echo
  echo "## Contents"
  for f in $FILES; do
    t=$(basename "$f" .md)
    echo "- $t"
  done
  echo
  for f in $FILES; do
    t=$(basename "$f" .md)
    echo "## ${t}"
    echo
    strip_one "$f"
    echo
  done
} > "$BODY"

# ---- AGENTS.md: only the repo-distill block (a pointer index built from the SPINE) ----
TITLE=$(awk '/^# /{sub(/^# /,""); sub(/: Knowledge Spine$/,""); print; exit}' "$SRC/SPINE.md")
BLOCK_BODY=$(mktemp)
{
  echo "<!-- Generated by repo-distill from .distill/. Edit .distill/, then run: $RENDER_CMD"
  echo "     Text outside this block is yours and is never touched. -->"
  echo "## How this repository works"
  echo
  echo "Durable knowledge, one file per area. Open the file that matches your task before you change anything."
  echo
  awk '/^## /{keep = ($0 !~ /[Pp]rovenance/)} keep && /^- /{gsub(/\]\(knowledge\//, "](.distill/knowledge/"); print}' "$SRC/SPINE.md"
} > "$BLOCK_BODY"
# A whole-file AGENTS.md from an older repo-distill becomes a title line plus the block.
if [ -f AGENTS.md ] && grep -q "GENERATED by repo-distill" AGENTS.md && ! grep -q "<!-- repo-distill:start -->" AGENTS.md; then
  printf '# %s\n' "${TITLE:-Agent guide}" > AGENTS.md
fi
[ -f AGENTS.md ] || printf '# %s\n' "${TITLE:-Agent guide}" > AGENTS.md
$BLOCK upsert AGENTS.md repo-distill --body-file "$BLOCK_BODY"
BLOCK_SHA=$($BLOCK sha AGENTS.md repo-distill)
rm -f "$BLOCK_BODY"

# ---- CLAUDE.md: Claude Code reads CLAUDE.md first, so it imports AGENTS.md ----
if [ ! -f CLAUDE.md ] || { grep -q "GENERATED by repo-distill" CLAUDE.md && ! grep -q "<!-- repo-distill:start -->" CLAUDE.md; }; then
  printf '@AGENTS.md\n' > CLAUDE.md
elif ! grep -q "@AGENTS.md" CLAUDE.md; then
  printf '@AGENTS.md\n' | $BLOCK upsert CLAUDE.md repo-distill
fi

# ---- Copilot (compiled copy; Copilot has no import mechanism) ----
mkdir -p .github
{ echo "$BANNER_TOP"; echo; cat "$BODY"; } > .github/copilot-instructions.md

# ---- manifest for the freshness gate ----
cat > "$SRC/.manifest" <<EOF
# repo-distill manifest, consumed by check-freshness.sh. Do not hand-edit.
sources_sha=$SRC_SHA
agents_block_sha=$BLOCK_SHA
copilot_sha=$(sha .github/copilot-instructions.md)
rendered_repo_state=$STAMP
adapters=AGENTS.md CLAUDE.md .github/copilot-instructions.md
EOF

rm -f "$BODY"
echo "rendered adapters from $(echo "$FILES" | wc -w | tr -d ' ') knowledge files:"
echo "  AGENTS.md (repo-distill block)  CLAUDE.md  .github/copilot-instructions.md"
echo "  sources_sha=$SRC_SHA"
