#!/usr/bin/env node
// Turns the 3D lock into the frames the installer and the plugin play: high-resolution renders from
// lock3d.mjs, converted cell by cell by chafa's shape matching (block symbols: bold solids, sharp edges),
// then parsed into cells { ch, fg, bg }. Run when the model changes; needs chafa (brew install chafa).
//   node tools/lock-frames.mjs            write design/lock-frames.json
//   node tools/lock-frames.mjs --strip    print frames 0, 8, 14, 21 side by side, for a look
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SIZES = { hero: '26x13', pane: '18x9' }
const dir = mkdtempSync(join(tmpdir(), 'amc-lock-'))
execFileSync('node', [join(ROOT, 'tools/lock3d.mjs'), '--png', dir])
const pngs = readdirSync(dir).filter(f => f.endsWith('.png')).sort()

// chafa's ANSI output into rows of cells; colors as #rrggbb, '' for the terminal's own
function parse(ansi) {
  const rows = []
  for (const line of ansi.replace(/\x1b\[\?25[lh]/g, '').split('\n')) {
    const row = []; let fg = '', bg = ''
    const re = /\x1b\[([0-9;]*)m|([^\x1b])/gu; let m
    while ((m = re.exec(line))) {
      if (m[2] !== undefined) { row.push({ ch: m[2], fg, bg }); continue }
      const p = m[1].split(';').map(Number)
      for (let i = 0; i < p.length; i++) {
        if (p[i] === 0) { fg = ''; bg = '' }
        else if (p[i] === 39) fg = ''
        else if (p[i] === 49) bg = ''
        else if ((p[i] === 38 || p[i] === 48) && p[i + 1] === 2) {
          const c = '#' + p.slice(i + 2, i + 5).map(v => v.toString(16).padStart(2, '0')).join('')
          if (p[i] === 38) fg = c; else bg = c
          i += 4
        }
      }
    }
    if (row.length) rows.push(row)
  }
  return rows
}

const out = { note: 'Generated by tools/lock-frames.mjs from tools/lock3d.mjs; do not edit.', sizes: {} }
for (const [name, size] of Object.entries(SIZES)) {
  out.sizes[name] = pngs.map(f => parse(execFileSync('chafa', ['-f', 'symbols', '--symbols', 'block+space', '--probe', 'off',
    '-c', 'full', '--color-extractor', 'median', '--dither', 'none', '--size', size, join(dir, f)], { encoding: 'utf8' })))
}
rmSync(dir, { recursive: true })

const paint = row => row.map(c => (c.bg ? `\x1b[48;2;${c.bg.slice(1).match(/../g).map(h => parseInt(h, 16)).join(';')}m` : '')
  + (c.fg ? `\x1b[38;2;${c.fg.slice(1).match(/../g).map(h => parseInt(h, 16)).join(';')}m` : '') + c.ch + '\x1b[0m').join('')
if (process.argv.includes('--strip')) {
  for (const name of ['hero', 'pane']) {
    const f = out.sizes[name], pick = [0, 8, 14, 21].map(i => f[Math.min(i, f.length - 1)])
    console.log(`  ${name}`)
    for (let r = 0; r < pick[0].length; r++) console.log('  ' + pick.map(fr => paint(fr[r] ?? [])).join('    '))
  }
} else {
  writeFileSync(join(ROOT, 'design/lock-frames.json'), JSON.stringify(out))
  console.log(`wrote design/lock-frames.json: ${pngs.length} frames, ${Object.keys(SIZES).join(' and ')}`)
}
